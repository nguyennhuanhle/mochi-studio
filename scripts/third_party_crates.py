"""Sinh legal/third-party-crates.txt: license của mọi crate Rust trong app (từ `cargo deny list`),
và chép license của Cap vào legal/ với tên riêng (installer MSI không cho hai file cùng tên gốc).
Chạy lại mỗi khi đổi dependency: python scripts/third_party_crates.py"""
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
out = subprocess.run(
    ["cargo", "deny", "--manifest-path", "apps/desktop/src-tauri/Cargo.toml", "list", "-l", "crate", "-f", "tsv"],
    cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True,
).stdout.splitlines()
header = out[0].split("\t")[1:]
lines = ["Mochi Studio — Rust crates bundled in the application and their licenses", "(generated by scripts/third_party_crates.py from `cargo deny list`)", ""]
for row in out[1:]:
    cols = row.split("\t")
    lic = [header[i] for i, v in enumerate(cols[1:]) if v.strip() == "X"]
    lines.append(f"{cols[0]}: {' OR '.join(lic) if lic else 'see NOTICE (internal crate)'}")
(ROOT / "legal" / "third-party-crates.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
shutil.copyfile(ROOT / "LICENSE", ROOT / "legal/LICENSE-AGPL-3.0.txt")
shutil.copyfile(ROOT / "vendor/cap/LICENSE", ROOT / "legal/CAP-LICENSE.txt")
shutil.copyfile(ROOT / "vendor/cap/licenses/LICENSE-MIT", ROOT / "legal/CAP-LICENSE-MIT.txt")
print(len(lines) - 3, "crate")
